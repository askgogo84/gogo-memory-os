// Generates app/dashboard-light.css from lib/dashboard/light-palette.mjs and the classes actually used in the
// dashboard. Run after adding a new dark colour: node scripts/gen-dashboard-light-css.mjs
// scripts/verify-dashboard-light-theme.mts fails if the file is out of date.
import { readFileSync, writeFileSync, readdirSync, statSync } from 'node:fs'
import { join } from 'node:path'
import { LIGHT_PALETTE } from '../lib/dashboard/light-palette.mjs'

const ROOTS = ['app/dashboard', 'components/dashboard']
const PROP = { bg: 'background-color', text: 'color', border: 'border-color' }
const STATES = { hover: ':hover', focus: ':focus', 'focus-within': ':focus-within', disabled: ':disabled', 'group-hover': null, placeholder: '::placeholder', active: ':active' }
const MEDIA = { sm: '40rem', md: '48rem', lg: '64rem', xl: '80rem' }

function walk(dir, out = []) {
  for (const name of readdirSync(dir)) {
    const p = join(dir, name)
    if (statSync(p).isDirectory()) walk(p, out)
    else if (p.endsWith('.tsx')) out.push(p)
  }
  return out
}
const esc = (cls) => cls.replace(/[^a-zA-Z0-9_-]/g, ch => '\\' + ch)
function alpha(hex, pct) {
  const h = hex.replace('#', '')
  const full = h.length === 3 ? h.split('').map(c => c + c).join('') : h
  const [r, g, b] = [0, 2, 4].map(i => parseInt(full.slice(i, i + 2), 16))
  return `rgba(${r},${g},${b},${pct / 100})`
}

export function buildLightCss() {
  const used = new Set()
  const re = /(?<![\w-])((?:[a-z-]+:)*)(bg|text|border)-\[(#[0-9a-fA-F]{3,8})\](?:\/(\d{1,3}))?(?![\w-])/g
  for (const file of ROOTS.flatMap(r => walk(r)).sort()) {
    const src = readFileSync(file, 'utf8')
    for (const m of src.matchAll(re)) used.add(m[0])
  }
  const rules = []
  for (const cls of [...used].sort()) {
    const m = cls.match(/^((?:[a-z-]+:)*)(bg|text|border)-\[(#[0-9a-fA-F]{3,8})\](?:\/(\d{1,3}))?$/)
    if (!m) continue
    const [, prefix, kind, hexRaw, opacity] = m
    const light = LIGHT_PALETTE[kind][hexRaw.toLowerCase()]
    if (!light) continue
    const value = opacity ? alpha(light, Number(opacity)) : light
    const variants = prefix ? prefix.slice(0, -1).split(':') : []
    let pseudo = '', media = '', group = false, ok = true
    for (const v of variants) {
      if (v in MEDIA) media = `@media (width >= ${MEDIA[v]})`
      else if (v === 'group-hover') group = true
      else if (v in STATES) pseudo += STATES[v]
      else ok = false
    }
    if (!ok) continue
    const target = (group ? '.group:hover ' : '') + '.' + esc(cls) + pseudo
    const rule = `.dashboard-root[data-theme='light'] ${target}{${PROP[kind]}:${value}}`
    rules.push(media ? `${media}{${rule}}` : rule)
  }
  return `/* Generated by scripts/gen-dashboard-light-css.mjs from lib/dashboard/light-palette.mjs. Do not edit by hand. */\n${rules.join('\n')}\n`
}

if (process.argv[1] && process.argv[1].endsWith('gen-dashboard-light-css.mjs')) {
  const css = buildLightCss()
  writeFileSync('app/dashboard-light.css', css)
  console.log(`app/dashboard-light.css: ${css.split('\n').length - 2} rules`)
}
